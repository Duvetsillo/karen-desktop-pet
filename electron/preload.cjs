const { contextBridge, ipcRenderer } = require('electron');
contextBridge.exposeInMainWorld('karen', {
  snapshot: () => ipcRenderer.invoke('snapshot'),
  settings: patch => ipcRenderer.invoke('settings', patch),
  credential: value => ipcRenderer.invoke('credential', value),
  connect: () => ipcRenderer.invoke('connect'),
  models: () => ipcRenderer.invoke('models'),
  selectModel: model => ipcRenderer.invoke('select-model', model),
  disconnect: () => ipcRenderer.invoke('disconnect'),
  send: (text, images) => ipcRenderer.invoke('send', text, images),
  abort: () => ipcRenderer.invoke('abort'),
  openSettings: () => ipcRenderer.invoke('open-settings'),
  hide: () => ipcRenderer.invoke('hide'),
  show: () => ipcRenderer.invoke('show'),
  contextMenu: () => ipcRenderer.invoke('context-menu'),
  hitTest: interactive => ipcRenderer.send('hit-test', interactive),
  drag: action => ipcRenderer.send('drag', action),
  synthesize: text => ipcRenderer.invoke('synthesize', text),
  prepareVoice: () => ipcRenderer.invoke('prepare-voice'),
  cancelSynthesis: () => ipcRenderer.invoke('cancel-synthesis'),
  voiceHealth: () => ipcRenderer.invoke('voice-health'),
  transcribe: pcm => ipcRenderer.invoke('transcribe', pcm),
  cancelTranscription: () => ipcRenderer.invoke('cancel-transcription'),
  demo: state => ipcRenderer.invoke('demo', state),
  energy: value => ipcRenderer.send('energy', value),
  listen: () => ipcRenderer.invoke('listen'),
  testVoice: () => ipcRenderer.invoke('test-voice'),
  chooseVoiceRoot: () => ipcRenderer.invoke('choose-voice-root'),
  captureSources: () => ipcRenderer.invoke('capture-sources'),
  captureScreen: id => ipcRenderer.invoke('capture-screen', id),
  pointAt: (id, x, y) => ipcRenderer.invoke('point-at', id, x, y),
  locateOnScreen: (id, description, image) => ipcRenderer.invoke('locate-on-screen', id, description, image),
  stopPointing: () => ipcRenderer.invoke('stop-pointing'),
  systemAudio: action => ipcRenderer.invoke('system-audio', action),
  captureStatus: status => ipcRenderer.send('capture-status', status),
  wakeStatus: status => ipcRenderer.send('wake-status', status),
  event: callback => { const listener = (_event, value) => callback(value); ipcRenderer.on('desktop-event', listener); return () => ipcRenderer.removeListener('desktop-event', listener); }
});
